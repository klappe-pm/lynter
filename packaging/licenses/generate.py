#!/usr/bin/env python3
"""Write packaging/licenses/rust-crates.txt: the license texts of every crate
compiled into the lynter binary and the WebAssembly build.

Run from the repository root:

    python3 packaging/licenses/generate.py          # rewrite the file
    python3 packaging/licenses/generate.py --check  # exit 1 when it is stale

The crate set is the normal (not dev, not build) dependency closure of
lynter-cli and lynter-wasm on every platform, read from `cargo metadata`.
License texts come from each crate's own published source, so the copyright
lines are the authors' own. Identical texts are printed once.
"""

import hashlib
import json
import pathlib
import subprocess
import sys

ROOTS = ("lynter-cli", "lynter-wasm")
OUTPUT = pathlib.Path(__file__).with_name("rust-crates.txt")
EXTRA = pathlib.Path(__file__).with_name("extra")
LICENSE_STEMS =("license", "licence", "copying", "unlicense", "notice")


def shipped_packages(meta):
    """Packages reachable from ROOTS through normal dependencies, workspace members excluded."""
    by_id = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    members = set(meta["workspace_members"])
    queue = [p["id"] for p in meta["packages"] if p["name"] in ROOTS and p["id"] in members]
    seen = set(queue)
    while queue:
        for dep in nodes[queue.pop()]["deps"]:
            normal = any(kind["kind"] is None for kind in dep["dep_kinds"])
            if normal and dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                queue.append(dep["pkg"])
    packages = [by_id[i] for i in seen if i not in members]
    return sorted(packages, key=lambda p: (p["name"], p["version"]))


def license_files(package):
    """License files at the top of a crate's source, sorted by name.

    A crate published without one falls back to extra/<crate>.txt, a copy of
    the license file in that crate's source repository.
    """
    root = pathlib.Path(package["manifest_path"]).parent
    found = sorted(
        f for f in root.iterdir()
        if f.is_file() and f.name.lower().startswith(LICENSE_STEMS)
    )
    extra = EXTRA / f"{package['name']}.txt"
    return found or ([extra] if extra.exists() else [])


def render():
    meta = json.loads(subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked"],
        check=True, capture_output=True, text=True,
    ).stdout)
    packages = shipped_packages(meta)
    texts = {}
    lines = [
        "Third-party Rust crates in Lynter",
        "",
        "The lynter binary and the WebAssembly build used by the Obsidian plugin and",
        "lynter.dev include the crates listed below. Each is used under the license",
        "its entry names; where a crate offers a choice, Lynter uses it under the MIT",
        "license when that is offered and under the first listed license otherwise.",
        "The license texts follow the list. Generated by packaging/licenses/generate.py.",
        "",
        "Crates",
        "",
    ]
    missing = []
    for package in packages:
        refs = []
        for path in license_files(package):
            text = path.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n").strip()
            key = hashlib.sha256(text.encode()).hexdigest()[:12]
            texts.setdefault(key, text)
            name = "LICENSE (from the source repository)" if path.parent == EXTRA else path.name
            refs.append(f"{name} [{key}]")
        if not refs:
            missing.append(f"{package['name']} {package['version']}")
        lines.append(f"{package['name']} {package['version']}")
        lines.append(f"  license: {package.get('license') or 'see license file'}")
        if package.get("repository"):
            lines.append(f"  source: {package['repository']}")
        lines.append(f"  texts: {', '.join(refs) if refs else 'none in the published crate'}")
        lines.append("")
    if missing:
        sys.exit("no license file in: " + ", ".join(missing))
    lines += ["License texts", ""]
    for key in sorted(texts):
        lines += ["=" * 78, f"[{key}]", "=" * 78, "", texts[key], ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            sys.exit(f"{OUTPUT} is stale: run python3 packaging/licenses/generate.py")
        print(f"{OUTPUT.name} is current")
        return
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT} ({text.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
