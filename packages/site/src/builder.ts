/**
 * Logic behind the config builder. The lynter.yaml text is the single source
 * of truth: the form reads values out of it and writes changes back into it
 * through the YAML document, so comments and key order the user already has
 * survive every edit, and typing in the YAML pane updates the form at once.
 */
import {isMap, parseDocument} from 'yaml';
import catalogJson from './rule-catalog.json';

export type OptionValue = boolean | number | string | unknown[] | Record<string, unknown>;

export interface CatalogRule {
  id: string;
  group: string;
  host: 'core' | 'code';
  description: string;
  options: Record<string, OptionValue>;
}

/** Every rule the engine ships, generated by `lynter rules --json`. */
export const catalog = catalogJson as CatalogRule[];

export type Path = (string | number)[];

export const EMPTY_CONFIG = 'version: 1\n';

/** Name of the browser storage slot that holds the draft between visits. */
export function draftSlot(): string {
  return ['lynter', 'builder', 'v1'].join('.');
}

export interface Parsed {
  /** The config as plain data, or null when the text is not a YAML mapping. */
  data: Record<string, unknown> | null;
  /** The first YAML syntax error, when there is one. */
  error: string | null;
}

export function parse(text: string): Parsed {
  const doc = parseDocument(text);
  if (doc.errors.length) return {data: null, error: doc.errors[0].message};
  const data = doc.toJS() as unknown;
  if (data === null || data === undefined) return {data: {}, error: null};
  if (typeof data !== 'object' || Array.isArray(data)) return {data: null, error: 'lynter.yaml must be a mapping of keys.'};
  return {data: data as Record<string, unknown>, error: null};
}

/** Read a nested value from parsed config data. */
export function getIn(data: unknown, path: Path): unknown {
  let at = data;
  for (const key of path) {
    if (at === null || typeof at !== 'object') return undefined;
    at = (at as Record<string | number, unknown>)[key];
  }
  return at;
}

const sameValue = (a: unknown, b: unknown) => JSON.stringify(a) === JSON.stringify(b);

/**
 * Write one value into the YAML text. `undefined` removes the key, and any
 * mapping left empty by a removal is removed with it, up to but not including
 * `keep` levels from the top. Returns the text unchanged when it cannot be parsed.
 */
export function setIn(text: string, path: Path, value: unknown, keep = 0): string {
  const doc = parseDocument(text.trim() ? text : EMPTY_CONFIG);
  if (doc.errors.length) return text;
  if (!isMap(doc.contents)) return text;
  if (value === undefined) {
    doc.deleteIn(path);
    for (let n = path.length - 1; n > keep; n--) {
      const parent = doc.getIn(path.slice(0, n));
      if (isMap(parent) && parent.items.length === 0) doc.deleteIn(path.slice(0, n));
      else break;
    }
  } else {
    doc.setIn(path, value);
  }
  return doc.toString({lineWidth: 0});
}

/** Where a rule stanza lives: the defaults, or one profile. */
export const rulesPath = (profile: string | null): Path => (profile === null ? ['defaults', 'rules'] : ['profiles', profile, 'rules']);

export interface RuleState {
  /** True when the file has a stanza for this rule in this scope. */
  present: boolean;
  enabled: boolean;
  /** Each option with its value in the file, or the rule's default. */
  options: Record<string, OptionValue>;
}

export function ruleState(data: unknown, profile: string | null, rule: CatalogRule): RuleState {
  const stanza = getIn(data, [...rulesPath(profile), rule.id]);
  const map = stanza !== null && typeof stanza === 'object' && !Array.isArray(stanza) ? (stanza as Record<string, OptionValue>) : null;
  const options: Record<string, OptionValue> = {};
  for (const [name, fallback] of Object.entries(rule.options)) options[name] = map && name in map ? map[name] : fallback;
  return {present: map !== null, enabled: map?.enabled === true, options};
}

export function setRuleEnabled(text: string, profile: string | null, id: string, enabled: boolean): string {
  return setIn(text, [...rulesPath(profile), id, 'enabled'], enabled);
}

/** Write an option, or drop it from the file when it is back at the rule's default. */
export function setRuleOption(text: string, profile: string | null, rule: CatalogRule, name: string, value: OptionValue): string {
  const path = [...rulesPath(profile), rule.id, name];
  return setIn(text, path, sameValue(value, rule.options[name]) ? undefined : value, path.length - 1);
}

/** Take a rule out of a scope entirely, so the scope above it decides. */
export function removeRule(text: string, profile: string | null, id: string): string {
  return setIn(text, [...rulesPath(profile), id], undefined, 0);
}

export function profileNames(data: unknown): string[] {
  const profiles = getIn(data, ['profiles']);
  return profiles !== null && typeof profiles === 'object' && !Array.isArray(profiles) ? Object.keys(profiles) : [];
}

/** A profile name that is safe as a YAML key and not taken yet. */
export function profileNameError(name: string, taken: string[]): string | null {
  if (!/^[a-z0-9][a-z0-9-]*$/.test(name)) return 'Use lowercase letters, digits and hyphens.';
  return taken.includes(name) ? 'A scope with this name already exists.' : null;
}

export function addProfile(text: string, name: string): string {
  return setIn(text, ['profiles', name], {match: {path: [`${name}/**`]}, rules: {}});
}

/** Lines of a textarea as a clean list: trimmed, blanks dropped. */
export const toList = (value: string): string[] => value.split('\n').map((l) => l.trim()).filter(Boolean);

export const asList = (value: unknown): string[] => (Array.isArray(value) ? value.map(String) : []);

/** The control an option gets, from the type of its default value. */
export function optionKind(value: OptionValue): 'toggle' | 'number' | 'text' | 'list' | 'yaml' {
  if (typeof value === 'boolean') return 'toggle';
  if (typeof value === 'number') return 'number';
  if (typeof value === 'string') return 'text';
  if (Array.isArray(value) && value.every((v) => typeof v === 'string')) return 'list';
  return 'yaml';
}

