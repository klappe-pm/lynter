//! `data.json` to `lynter.yaml` text.

use super::parse_config;
use crate::notetypes::format::to_yaml;
use serde_json::{Map, Value};

/// Keys data.json keeps for UI state only; they are not migrated.
const UI_STATE_KEYS: [&str; 11] = [
    "lintOnSave",
    "displayChanged",
    "suppressMessageWhenNoChange",
    "suppressLintAllFilesConfirmationModal",
    "suppressLintAllFilesInFolderConfirmationModal",
    "settingsConvertedToConfigKeyValues",
    "recordLintOnSaveLogs",
    "lintOnFileChange",
    "displayLintOnFileChangeNotice",
    "linterLocale",
    "logLevel",
];

/// `JSON.stringify` for the comment block: integral floats print as integers.
fn js_json(v: &Value) -> String {
    match v {
        Value::Number(n) => crate::notetypes::format::scalar(&Value::Number(n.clone())),
        Value::Array(a) => format!("[{}]", a.iter().map(js_json).collect::<Vec<_>>().join(",")),
        Value::Object(m) => format!(
            "{{{}}}",
            m.iter()
                .map(|(k, v)| format!("{}:{}", Value::String(k.clone()), js_json(v)))
                .collect::<Vec<_>>()
                .join(",")
        ),
        other => other.to_string(),
    }
}

/// Map a plugin data.json to lynter.yaml text. Conservative: `ruleConfigs`
/// become `defaults.rules`, `foldersToIgnore` becomes `ignore.folders`,
/// UI-state keys stay behind, and everything else is carried as comments.
/// Input that already parses as a valid config is returned unchanged.
pub fn migrate_data_json(data_json: &str) -> Result<String, String> {
    if parse_config(data_json).is_ok() {
        return Ok(data_json.to_owned());
    }
    let data: Value = serde_json::from_str(data_json)
        .map_err(|e| format!("data.json is neither a valid lynter.yaml nor valid JSON: {e}"))?;
    let Value::Object(data) = data else {
        return Err("data.json must be a JSON object".to_owned());
    };
    let mut unmapped: Vec<(String, Value)> = Vec::new();
    let mut rules = Map::new();
    if let Some(rc) = data.get("ruleConfigs") {
        if let Value::Object(rc) = rc {
            for (id, options) in rc {
                let mappable = options
                    .as_object()
                    .is_some_and(|o| o.get("enabled").is_none_or(Value::is_boolean));
                if mappable {
                    rules.insert(id.clone(), options.clone());
                } else {
                    unmapped.push((format!("ruleConfigs.{id}"), options.clone()));
                }
            }
        } else {
            unmapped.push(("ruleConfigs".to_owned(), rc.clone()));
        }
    }
    let mut ignore_folders: Option<&Vec<Value>> = None;
    if let Some(f) = data.get("foldersToIgnore") {
        match f {
            Value::Array(a) if a.iter().all(Value::is_string) => ignore_folders = Some(a),
            other => unmapped.push(("foldersToIgnore".to_owned(), other.clone())),
        }
    }
    for (k, v) in &data {
        if k == "ruleConfigs" || k == "foldersToIgnore" || UI_STATE_KEYS.contains(&k.as_str()) {
            continue;
        }
        unmapped.push((k.clone(), v.clone()));
    }
    let mut config = Map::new();
    config.insert("version".into(), Value::from(1));
    if !rules.is_empty() {
        let mut d = Map::new();
        d.insert("rules".into(), Value::Object(rules));
        config.insert("defaults".into(), Value::Object(d));
    }
    if let Some(f) = ignore_folders.filter(|f| !f.is_empty()) {
        let mut i = Map::new();
        i.insert("folders".into(), Value::Array(f.clone()));
        config.insert("ignore".into(), Value::Object(i));
    }
    let mut lines = vec![
        "# lynter.yaml generated by lynter from data.json.".to_owned(),
        "# UI-only settings (save/notice/locale/log toggles) stay in data.json by design."
            .to_owned(),
        to_yaml(&Value::Object(config)),
    ];
    if !unmapped.is_empty() {
        lines.push(String::new());
        lines.push(
            "# unmapped: the data.json settings below have no lynter.yaml equivalent yet."
                .to_owned(),
        );
        lines.push(
            "# They were carried over as comments so nothing is dropped silently.".to_owned(),
        );
        for (k, v) in &unmapped {
            lines.push(format!("# {k}: {}", js_json(v)));
        }
    }
    Ok(lines.join("\n") + "\n")
}
